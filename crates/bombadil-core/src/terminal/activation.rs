use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

/// A shell family Bombadil knows how to re-assert activation in.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShellFamily {
    Bash,
    Zsh,
    Fish,
    PosixSh,
    Unknown,
}

impl ShellFamily {
    /// Recognise by file name, so `/opt/homebrew/bin/bash` is still bash.
    pub fn detect(shell_path: &str) -> Self {
        let name = Path::new(shell_path)
            .file_stem()
            .map(|s| s.to_string_lossy().to_ascii_lowercase())
            .unwrap_or_default();
        match name.as_str() {
            "bash" => ShellFamily::Bash,
            "zsh" => ShellFamily::Zsh,
            "fish" => ShellFamily::Fish,
            "sh" | "dash" | "ash" => ShellFamily::PosixSh,
            _ => ShellFamily::Unknown,
        }
    }
}

/// A generated startup file that re-asserts activation after the user's own
/// shell configuration has run.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InitFile {
    /// Where to write it, relative to a Bombadil-owned temporary directory.
    pub relative_path: PathBuf,
    pub contents: String,
    /// Arguments the shell must be started with. `{file}` is replaced with the
    /// written file's absolute path by the caller.
    pub shell_args: Vec<String>,
    /// Environment the shell must be started with. `{dir}` is replaced with
    /// the containing directory's absolute path by the caller.
    pub env: BTreeMap<String, String>,
}

/// Escape a path for single-quoted POSIX shell context.
fn sq(path: &Path) -> String {
    path.to_string_lossy().replace('\'', r"'\''")
}

/// Escape a path for single-quoted fish context.
///
/// fish's single quotes honour only `\\` and `\'`, so the POSIX `'\''` dance
/// that [`sq`] produces would be inserted literally and break the command.
fn sq_fish(path: &Path) -> String {
    path.to_string_lossy()
        .replace('\\', "\\\\")
        .replace('\'', "\\'")
}

/// Build the startup file that puts the venv back at the front of `PATH`.
///
/// Verified on a real machine: passing `PATH=<venv>/bin:$PATH` to an
/// interactive bash leaves `<venv>/bin` at position 3, behind `~/.local/bin`,
/// because `.bashrc` prepends after we set it. Only something running after
/// the user's rc can win, so we source their configuration first and prepend
/// afterwards.
///
/// Returns `None` for a shell we do not know, because a bash rcfile handed to
/// nushell would fail on every launch — losing the re-assertion is better than
/// a syntax error every time.
pub fn init_file(family: ShellFamily, venv_bin: &Path) -> Option<InitFile> {
    let bin = sq(venv_bin);
    match family {
        // TODO(windows): a Windows-style venv path is unusable in a Git Bash
        // `PATH`. Inside Git Bash the separator IS `:`, and a Windows path
        // contains one right after the drive letter, so
        // `export PATH='C:\Users\...\Scripts':"$PATH"` is read as two
        // entries -- `C` and `\Users\...\Scripts` -- neither of which exists.
        // The path would have to be converted to POSIX form
        // (`/c/Users/.../Scripts`) first. Not reachable in production today:
        // `GitBash` is in the `PathOnly` bucket and its argv arm drops
        // `shell_args` entirely, so this file is never sourced there. It
        // goes live the moment anyone moves `GitBash` to `Full`, which is
        // exactly the kind of well-meaning change made later -- see the
        // matching TODO(windows) on Git Bash detection in detect.rs.
        ShellFamily::Bash => Some(InitFile {
            relative_path: PathBuf::from("bombadil-bashrc"),
            // Known limitation: most distro-default ~/.bash_profile files
            // already source ~/.bashrc themselves, so sourcing both here
            // commonly runs .bashrc twice. Our own prepend still runs exactly
            // once afterwards, so activation is unaffected — but a user's
            // non-idempotent tool-init lines (nvm, pyenv, rbenv) can
            // double-prepend their own entries. Cosmetic PATH bloat that
            // Bombadil amplifies rather than causes.
            contents: format!(
                "# Generated by Bombadil. Sources your configuration first, then\n\
                 # re-asserts the virtual environment, which your rc may otherwise\n\
                 # push off the front of PATH.\n\
                 [ -f \"$HOME/.bash_profile\" ] && . \"$HOME/.bash_profile\"\n\
                 [ -f \"$HOME/.bashrc\" ] && . \"$HOME/.bashrc\"\n\
                 export PATH='{bin}':\"$PATH\"\n"
            ),
            // NOT -l: bash silently ignores --rcfile for login shells.
            shell_args: vec!["--rcfile".into(), "{file}".into(), "-i".into()],
            env: BTreeMap::new(),
        }),
        ShellFamily::Zsh => Some(InitFile {
            relative_path: PathBuf::from(".zshrc"),
            // Setting ZDOTDIR means zsh reads $ZDOTDIR/.zshenv instead of
            // $HOME/.zshenv, so a user following zsh's own convention of
            // putting environment setup there (asdf, nix and pyenv hooks
            // commonly land in .zshenv) would get a Bombadil terminal subtly
            // unlike every other terminal they open. Source it first, in
            // zsh's own order: .zshenv, then .zshrc.
            contents: format!(
                "# Generated by Bombadil. See the bash file for why this exists.\n\
                 [ -f \"$HOME/.zshenv\" ] && . \"$HOME/.zshenv\"\n\
                 [ -f \"$HOME/.zshrc\" ] && . \"$HOME/.zshrc\"\n\
                 export PATH='{bin}':\"$PATH\"\n"
            ),
            shell_args: vec!["-i".into()],
            env: BTreeMap::from([("ZDOTDIR".to_string(), "{dir}".to_string())]),
        }),
        ShellFamily::Fish => Some(InitFile {
            relative_path: PathBuf::from("bombadil.fish"),
            // --move is load-bearing, not decoration: `compose` has already
            // put the venv on PATH by the time this runs, and fish_add_path
            // is idempotent -- without --move it sees the component already
            // present and does nothing at all, leaving it wherever
            // config.fish demoted it. Exactly the silent no-op this file
            // exists to prevent.
            contents: format!("fish_add_path --move --prepend --path '{bin}'\n"),
            // `-C` (run a command before reading config) requires fish >= 3.4
            // (released 2022). No version guard exists here and none is
            // planned; noted so the next person does not think it was
            // overlooked.
            shell_args: vec!["-C".into(), "source {file}".into(), "-i".into()],
            env: BTreeMap::new(),
        }),
        ShellFamily::PosixSh => Some(InitFile {
            relative_path: PathBuf::from("bombadil-env.sh"),
            contents: format!(
                "[ -f \"$HOME/.profile\" ] && . \"$HOME/.profile\"\n\
                 export PATH='{bin}':\"$PATH\"\n"
            ),
            shell_args: vec!["-i".into()],
            env: BTreeMap::from([("ENV".to_string(), "{file}".to_string())]),
        }),
        ShellFamily::Unknown => None,
    }
}

/// A command that activates `venv_bin`'s venv from *inside* an already-running
/// interactive shell, by sourcing the venv's own activate script.
///
/// This is the sibling of [`init_file`] for terminals that cannot be handed a
/// shell binary plus arguments. `init_file` only works when the launch can
/// pass `--rcfile`/`ZDOTDIR`/`-C`, because it has to run *before* the user's
/// rc; this one runs *after* it, which is what a terminal that executes a
/// startup command in its own pane gives us (see `terminal/warp.rs`). Order is
/// still what makes it correct: sourcing after the rc means nothing can demote
/// the venv afterwards.
///
/// Returns `None` for a shell we do not know. Sourcing the POSIX `activate`
/// into nushell would be a syntax error on every launch, and an unactivated
/// shell the user can still type into beats a broken one -- the same rule
/// `init_file` follows.
pub fn activate_command(family: ShellFamily, venv_bin: &Path) -> Option<String> {
    let (script, escape): (PathBuf, fn(&Path) -> String) = match family {
        ShellFamily::Bash | ShellFamily::Zsh | ShellFamily::PosixSh => {
            (venv_bin.join("activate"), sq)
        }
        // fish cannot source the POSIX script; uv writes it a fish one.
        ShellFamily::Fish => (venv_bin.join("activate.fish"), sq_fish),
        ShellFamily::Unknown => return None,
    };
    Some(format!("source '{}'", escape(&script)))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::Path;

    #[test]
    fn a_shell_is_recognised_by_its_file_name_not_its_directory() {
        assert_eq!(ShellFamily::detect("/usr/bin/bash"), ShellFamily::Bash);
        assert_eq!(ShellFamily::detect("/bin/zsh"), ShellFamily::Zsh);
        assert_eq!(
            ShellFamily::detect("/usr/local/bin/fish"),
            ShellFamily::Fish
        );
        assert_eq!(ShellFamily::detect("/bin/sh"), ShellFamily::PosixSh);
        assert_eq!(ShellFamily::detect("/usr/bin/nu"), ShellFamily::Unknown);
    }

    #[test]
    fn a_bash_users_own_rc_is_sourced_before_we_prepend() {
        // Order is the whole point: sourcing after our prepend would let the
        // user's rc demote the venv again, which is the bug this file exists
        // to fix.
        let file = init_file(ShellFamily::Bash, Path::new("/envs/api/bin")).unwrap();
        let src = file
            .contents
            .find(".bashrc")
            .expect("must source ~/.bashrc");
        let prepend = file.contents.find("/envs/api/bin").expect("must prepend");
        assert!(src < prepend, "got {}", file.contents);
    }

    #[test]
    fn bash_is_started_interactive_and_not_as_a_login_shell() {
        // Verified: bash silently ignores --rcfile when started with -l, so a
        // login shell would never source our file at all.
        let file = init_file(ShellFamily::Bash, Path::new("/envs/api/bin")).unwrap();
        assert!(file.shell_args.iter().any(|a| a == "--rcfile"));
        assert!(file.shell_args.iter().any(|a| a == "-i"));
        assert!(
            !file.shell_args.iter().any(|a| a == "-l" || a == "--login"),
            "got {:?}",
            file.shell_args
        );
    }

    #[test]
    fn zsh_uses_zdotdir_rather_than_an_argument() {
        let file = init_file(ShellFamily::Zsh, Path::new("/envs/api/bin")).unwrap();
        assert_eq!(file.relative_path, std::path::PathBuf::from(".zshrc"));
        assert_eq!(file.env.get("ZDOTDIR").map(String::as_str), Some("{dir}"));

        // ZDOTDIR redirects .zshenv too, so unless we source it the user
        // loses whatever asdf/nix/pyenv hook lives there -- the bash arm
        // sources both .bash_profile and .bashrc, and this is the same
        // requirement. Order matters: zsh reads .zshenv before .zshrc.
        let zshenv = file.contents.find(".zshenv").expect("must source .zshenv");
        let zshrc = file.contents.find(".zshrc").expect("must source .zshrc");
        assert!(zshenv < zshrc, "got {}", file.contents);
        let prepend = file.contents.find("/envs/api/bin").expect("must prepend");
        assert!(zshrc < prepend, "got {}", file.contents);
    }

    #[test]
    fn fish_prepends_with_its_own_builtin() {
        let file = init_file(ShellFamily::Fish, Path::new("/envs/api/bin")).unwrap();
        assert!(
            file.contents.contains("fish_add_path"),
            "got {}",
            file.contents
        );
        assert!(file.contents.contains("--prepend"), "got {}", file.contents);
    }

    #[test]
    fn fish_moves_the_venv_rather_than_relying_on_it_being_absent() {
        // fish_add_path is idempotent: it will NOT move a component that is
        // already in $PATH unless --move is given. `compose` has already put
        // the venv on PATH before this file runs, so without --move the
        // command is a complete no-op and the venv stays wherever
        // config.fish demoted it -- activation silently fails while `open`
        // still returns Ok. fish is not installed here and is not on CI
        // runners, so this unit test is the only place the requirement can
        // be held.
        let file = init_file(ShellFamily::Fish, Path::new("/envs/api/bin")).unwrap();
        assert!(
            file.contents.contains("--move"),
            "without --move fish_add_path does nothing; got {}",
            file.contents
        );
    }

    #[test]
    fn an_unknown_shell_gets_no_init_file_rather_than_a_broken_one() {
        // A bash rcfile handed to nushell would produce a syntax error on
        // every terminal launch, which is worse than losing the reassertion.
        assert!(init_file(ShellFamily::Unknown, Path::new("/envs/api/bin")).is_none());
    }

    #[test]
    fn a_venv_path_containing_a_quote_is_escaped() {
        // A previous branch on this project shipped an unquoted interpolation
        // that broke every launch for users with an apostrophe in their path.
        let file = init_file(ShellFamily::Bash, Path::new("/home/o'brien/env/bin")).unwrap();
        assert!(
            file.contents.contains(r"'/home/o'\''brien/env/bin'"),
            "the apostrophe must be escaped; got {}",
            file.contents
        );
        assert!(
            !file.contents.contains("'/home/o'brien/env/bin'"),
            "the raw path must never appear unescaped; got {}",
            file.contents
        );
    }

    #[test]
    fn fish_also_escapes_a_quote_in_the_venv_path() {
        // fish's contents are built through the same `sq` helper as bash; this
        // pins that the escaping is not bash-only.
        let file = init_file(ShellFamily::Fish, Path::new("/home/o'brien/env/bin")).unwrap();
        assert!(
            file.contents.contains(r"'/home/o'\''brien/env/bin'"),
            "the apostrophe must be escaped; got {}",
            file.contents
        );
        assert!(
            !file.contents.contains("'/home/o'brien/env/bin'"),
            "the raw path must never appear unescaped; got {}",
            file.contents
        );
    }

    #[test]
    fn posix_sh_sources_profile_before_prepending_and_sets_env() {
        let file = init_file(ShellFamily::PosixSh, Path::new("/envs/api/bin")).unwrap();
        let src = file
            .contents
            .find(".profile")
            .expect("must source ~/.profile");
        let prepend = file.contents.find("/envs/api/bin").expect("must prepend");
        assert!(src < prepend, "got {}", file.contents);
        assert_eq!(file.env.get("ENV").map(String::as_str), Some("{file}"));
    }

    #[test]
    fn posix_shells_activate_by_sourcing_the_venvs_own_script() {
        // The whole point of this sibling to `init_file`: no --rcfile/ZDOTDIR
        // flag is needed, because the command is typed into a shell that has
        // already read its rc. Verified end to end against warp-terminal
        // 0.2026.09.16 -- see terminal/warp.rs.
        //
        // The expectation is built through `Path::join` rather than written out
        // with `/`: on the Windows runner `join` produces `\`. Comparing the
        // whole string is still safe here because `sq` escapes quotes only and
        // leaves separators alone.
        let bin = Path::new("/envs/api/bin");
        let expected = format!("source '{}'", bin.join("activate").display());
        for family in [ShellFamily::Bash, ShellFamily::Zsh, ShellFamily::PosixSh] {
            let cmd = activate_command(family, bin).unwrap();
            assert_eq!(cmd, expected);
        }
    }

    #[test]
    fn fish_activates_with_its_own_script_not_the_posix_one() {
        // Sourcing the POSIX activate into fish fails: `export` is not fish
        // syntax. uv writes activate.fish alongside activate, and picking the
        // wrong one would look like a working launch and leave the venv
        // inactive.
        //
        // Asserted by shape rather than by whole string, unlike the POSIX test
        // above: `sq_fish` also doubles backslashes, so an exact expectation
        // would have to encode this host's separator and would fail on Windows
        // for a reason that has nothing to do with the script chosen.
        let bin = Path::new("/envs/api/bin");
        let cmd = activate_command(ShellFamily::Fish, bin).unwrap();
        assert!(cmd.starts_with("source '"), "got {cmd}");
        assert!(cmd.ends_with("activate.fish'"), "got {cmd}");
        assert_ne!(
            cmd,
            activate_command(ShellFamily::Bash, bin).unwrap(),
            "fish must not be handed the POSIX script"
        );
    }

    #[test]
    fn an_unknown_shell_gets_no_activation_command_rather_than_a_broken_one() {
        assert!(activate_command(ShellFamily::Unknown, Path::new("/envs/api/bin")).is_none());
    }

    #[test]
    fn a_quote_in_the_venv_path_is_escaped_for_posix_shells() {
        let cmd = activate_command(ShellFamily::Bash, Path::new("/home/o'brien/env/bin")).unwrap();
        // The '\'' dance closes the quote, emits a literal one and reopens it.
        // Without it the shell sees an unterminated string and the launch
        // fails every time -- but only for users whose path contains a quote,
        // so this is worth pinning on its own.
        assert!(cmd.contains(r"'\''"), "got {cmd}");
        assert!(cmd.starts_with("source '"), "got {cmd}");
        assert!(cmd.ends_with("activate'"), "got {cmd}");
    }

    #[test]
    fn a_quote_in_the_venv_path_is_escaped_the_fish_way() {
        // fish honours only \\ and \' inside single quotes, so the POSIX
        // '\'' form would arrive literally and the source would fail.
        let cmd = activate_command(ShellFamily::Fish, Path::new("/home/o'brien/env/bin")).unwrap();
        assert!(cmd.contains(r"\'"), "got {cmd}");
        assert!(
            !cmd.contains(r"'\''"),
            "the POSIX form is literal text in fish; got {cmd}"
        );
        assert!(cmd.ends_with("activate.fish'"), "got {cmd}");
    }
}
